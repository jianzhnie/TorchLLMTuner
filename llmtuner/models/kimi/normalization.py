"""Kimi RMS normalization preserving upstream float32 reduction order."""

import torch
from torch import nn


class KimiRMSNorm(nn.Module):
    def __init__(self, hidden_size: int, eps: float = 1e-6) -> None:
        super().__init__()
        self.weight = nn.Parameter(torch.ones(hidden_size))
        self.variance_epsilon = eps

    def forward(self, hidden_states: torch.Tensor) -> torch.Tensor:
        dtype = hidden_states.dtype
        values = hidden_states.float()
        values = values * torch.rsqrt(
            values.square().mean(-1, keepdim=True) + self.variance_epsilon
        )
        return self.weight * values.to(dtype)


class KimiGatedRMSNorm(KimiRMSNorm):
    """Normalize each value head before applying its sigmoid output gate."""

    def forward(self, hidden_states: torch.Tensor, gate: torch.Tensor) -> torch.Tensor:
        return super().forward(hidden_states) * gate.float().sigmoid().to(
            hidden_states.dtype
        )
